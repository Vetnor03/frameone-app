#!/usr/bin/env python3
"""Generate ESM GFX glyph measurement table from an immutable F1 metrics snapshot.

The snapshot contains only glyph extents/advance/bearings, NEVER bitmap pixels.
Generated output is for JS/CI candidate geometry only; firmware uses original F2.
"""
import json
import sys
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
source=ROOT/"shared/date-gfx-metrics.json"
out=ROOT/"app/lib/dateGfxMetrics.generated.mjs"
content=json.loads(source.read_text(encoding="utf-8"))
assert content["measurementOnly"] is True
assert content["fields"]==["width","height","xAdvance","xOffset","yOffset"]
assert content["glyphOrder"]=="0x20..0xFF"
assert set(content["fonts"])=={"Fraunces72","Fraunces48","DM24","DM18"}
assert all(len(rows)==224 and all(len(g)==5 for g in rows) for rows in content["fonts"].values())
data=json.dumps(content["fonts"],separators=(",",":"),ensure_ascii=False)
expected="// GENERATED by shared/generate_date_gfx_metrics.py; DO NOT EDIT.\n"
expected+="// Measurement-only: real F1 GFX metrics (no bitmap or rendering assets).\n"
expected+="export const DateGfxGlyphs = Object.freeze("+data+")\n"
if len(sys.argv)==2 and sys.argv[1]=="--check":
    assert out.exists() and out.read_text(encoding="utf-8")==expected,"date GFX metrics generated binding stale"
elif len(sys.argv)==1:
    out.write_text(expected,encoding="utf-8")
else:
    raise SystemExit("usage: generate_date_gfx_metrics.py [--check]")
print("date GFX metric binding checked" if len(sys.argv)==2 else "date GFX metric binding generated")
