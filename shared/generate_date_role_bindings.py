#!/usr/bin/env python3
"""Generate both standalone geometry bindings from the ONE shared policy JSON.

This does not activate a renderer. Usage: python3 shared/generate_date_role_bindings.py
For CI freshness checking: python3 shared/generate_date_role_bindings.py --check
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
policy = json.loads((ROOT / "shared/date-element-policy.json").read_text(encoding="utf-8"))
m = policy["panel"]["matte"]
g = policy["candidateGeometry"]
vals = {
    "MATTE_X": m["x"], "MATTE_Y": m["y"],
    "MATTE_WIDTH": m["width"], "MATTE_HEIGHT": m["height"],
    "INSET_TIGHT": g["inset"]["tight"], "INSET_REGULAR": g["inset"]["regular"],
    "INSET_SPACIOUS": g["inset"]["spacious"],
    "TIGHT_WIDTH_EXCLUSIVE": g["inset"]["tightWidthExclusive"],
    "TIGHT_HEIGHT_EXCLUSIVE": g["inset"]["tightHeightExclusive"],
    "SPREAD_MIN_WIDTH": g["spread"]["minWidth"],
    "SPREAD_MIN_HEIGHT": g["spread"]["minHeight"],
    "GAP_TIGHT": g["gap"]["tight"], "GAP_REGULAR": g["gap"]["regular"],
    "GAP_SPACIOUS": g["gap"]["spacious"],
}
assert policy["measuredPlanner"]["candidateExpressions"] == ["stack", "ribbon", "card"]
assert policy["measuredPlanner"]["requiredFacts"] == ["month", "day", "weekday"]
assert all(isinstance(n, int) and n >= 0 for n in vals.values())

cpp = (
    "// GENERATED by shared/generate_date_role_bindings.py; DO NOT EDIT.\n"
    "#pragma once\nnamespace DateRolePolicy {\n"
    + "".join("static const int %s = %s;\n" % (key, value) for key, value in vals.items())
    + "}  // namespace DateRolePolicy\n"
)
js = (
    "// GENERATED by shared/generate_date_role_bindings.py; DO NOT EDIT.\n"
    "export const DateRolePolicy = Object.freeze({\n"
    + "".join("  %s: %s,\n" % (key, value) for key, value in vals.items())
    + "})\n"
)
targets = [
    (ROOT / "frame/src/display/DateRolePolicy.generated.h", cpp),
    (ROOT / "app/lib/dateRolePolicy.generated.mjs", js),
]
check = sys.argv[1:] == ["--check"]
if not (check or not sys.argv[1:]):
    raise SystemExit("usage: generate_date_role_bindings.py [--check]")
for target, content in targets:
    if check:
        if not target.exists() or target.read_text(encoding="utf-8") != content:
            raise SystemExit("Generated binding is stale: %s" % target)
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8")
print("Date role bindings %s" % ("up to date" if check else "generated"))
