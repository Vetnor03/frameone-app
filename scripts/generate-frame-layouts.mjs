import { readFile, writeFile } from 'node:fs/promises'

const source = JSON.parse(await readFile(new URL('../shared/frame-layouts.json', import.meta.url), 'utf8'))
const size = { SMALL: 'CELL_SMALL', MEDIUM: 'CELL_MEDIUM', LARGE: 'CELL_LARGE', XL: 'CELL_XL' }
const names = ['full', 'default', 'pyramid', 'square']
let out = `// Generated by scripts/generate-frame-layouts.mjs. Do not edit.\n#pragma once\n#include "Types.h"\n\nnamespace GeneratedLayouts {\n`
for (const name of names) {
  const id = name.toUpperCase()
  out += `static const GridCell ${id}[] = {\n`
  for (const c of source.layouts[name]) out += `  {${c.col}, ${c.row}, ${c.colSpan}, ${c.rowSpan}, ${c.slot}, ${size[c.size]}},\n`
  out += `};\nstatic const int ${id}_COUNT = sizeof(${id}) / sizeof(${id}[0]);\n`
}
out += `}\n`
const target = new URL('../frame/src/core/GeneratedLayouts.h', import.meta.url)
if (process.argv.includes('--check')) {
  const current = await readFile(target, 'utf8').catch(() => '')
  if (current !== out) { console.error('GeneratedLayouts.h is stale'); process.exitCode = 1 }
} else await writeFile(target, out)
